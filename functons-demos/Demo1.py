# write function to add two numbers and return the addition

# function definition
def add(number1, number2):
    return number1 + number2

def subtract(number1, number2):
    return number1 - number2

def multiply(number1, number2):
    return number1 * number2

def divide(number1, number2):
    return number1 / number2

def pow(number1, number2):
    return number1 ** number2


# function call
print('addition of two numbers is ', add(100, 200))
print('subtraction of two numbers is ', subtract(100, 200))
print('multiplication of two numbers is ', multiply(100, 200))
print('division of two numbers is ', divide(100, 200))
print('pow of two numbers is ', pow(2, 5))
